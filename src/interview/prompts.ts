/** 系统级 prompt：定义面试官角色 */
export function buildInterviewSystemPrompt(
  position: string,
  difficulty: string,
): string {
  const focus =
    POSITION_FOCUS[position] ?? '该岗位通用核心知识、项目经验与解决问题的思路';
  const strategy =
    DIFFICULTY_STRATEGY[difficulty] ??
    '根据候选人回答水平动态调整问题深度';

  return `你是一位资深技术面试官，正在面试一位【${position}】岗位的候选人，本场面试难度为【${difficulty}】。

# 岗位考察重点
${focus}

# 本场难度策略
${strategy}

# 通用面试规则
1. 每次只问一个问题；候选人回答后，先给一两句**有针对性**的反馈（点出对/错/含糊的地方），再继续追问或进入下一题。
2. 禁止机械堆问题；如果候选人回答暴露盲点，应在同一题内追问，而不是换题敷衍。
3. 不要预先公布"标准答案"；评分与参考答案留到最终报告环节。
4. 全程中文，专业、克制、不阿谀；候选人答错时直接指出，不打圆场。
5. 单次发言控制在 200 字以内，避免大段说教挤占候选人思考空间。`;
}

/** 开场白 prompt */
export const INTERVIEW_GREETING_PROMPT =
  '请用中文向候选人打招呼，介绍你是面试官，并开始第一个面试问题。直接输出你的发言，不要加解释。';

/** 中间问题反馈 + 下一题 prompt */
export function buildNextQuestionPrompt(
  current: number,
  total: number,
): string {
  return `这是第 ${current}/${total} 个问题。请对候选人刚才的回答给出一两句简短反馈，然后提出下一个面试问题。用中文。`;
}

/** 续玩时的过渡 prompt */
export function buildResumePrompt(current: number, total: number): string {
  return `继续之前的面试。请先简短回顾上一题并过渡，然后提出第 ${current}/${total} 个问题。用中文。`;
}

