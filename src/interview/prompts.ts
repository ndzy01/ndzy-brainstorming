/** 单题标准答案 prompt */
export function buildStandardAnswerPrompt(question: string): string {
  return `你是一位资深技术面试官。以下是你在面试中提出的一个问题，请给出该问题的标准答案或理想回答要点（用中文，简明扼要）：

【面试问题】
${question}

【标准答案/参考要点】`;
}
